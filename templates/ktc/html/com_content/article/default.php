/*
 * KTC — override de la vue article de com_content (copie de la vue du noyau
 * Joomla 6.2.0, components/com_content/tmpl/article/default.php). UN SEUL
 * écart : la fiche chantier (arbitrage B du laboratoire M02), mise en forme
 * automatiquement en tête d'article à partir des champs personnalisés du
 * groupe « Fiche chantier » (M01) — voir css/template.css section 11 et
 * docs/guides/04-articles-et-chantiers.md.
 * À chaque mise à jour du cœur (via PR, décision D16), vérifier si la vue
 * d'origine évolue et reporter les changements ici.
 */

use Joomla\CMS\Factory;
use Joomla\CMS\HTML\HTMLHelper;
use Joomla\CMS\Language\Associations;
use Joomla\CMS\Language\Text;
use Joomla\CMS\Layout\FileLayout;
use Joomla\CMS\Layout\LayoutHelper;
use Joomla\CMS\Router\Route;
use Joomla\CMS\Uri\Uri;
use Joomla\Component\Content\Administrator\Extension\ContentComponent;
use Joomla\Component\Content\Site\Helper\RouteHelper;

/** @var \Joomla\Component\Content\Site\View\Article\HtmlView $this */
// Create shortcuts to some parameters.
$params  = $this->item->params;
$canEdit = $params->get('access-edit');
$user    = $this->getCurrentUser();
$info    = $params->get('info_block_position', 0);
$htag    = $this->params->get('show_page_heading') ? 'h2' : 'h1';

// Check if associations are implemented. If they are, define the parameter.
$assocParam        = (Associations::isEnabled() && $params->get('show_associations'));
$currentDate       = Factory::getDate()->format('Y-m-d H:i:s');
$isNotPublishedYet = $this->item->publish_up > $currentDate;
$isExpired         = !is_null($this->item->publish_down) && $this->item->publish_down < $currentDate;
?>
<div class="com-content-article item-page<?php echo $this->pageclass_sfx; ?>">
    <meta itemprop="inLanguage" content="<?php echo ($this->item->language === '*') ? Factory::getApplication()->get('language') : $this->item->language; ?>">
    <?php if ($this->params->get('show_page_heading')) : ?>
    <div class="page-header">
        <h1> <?php echo $this->escape($this->params->get('page_heading')); ?> </h1>
    </div>
    <?php endif;
    if (!empty($this->item->pagination) && !$this->item->paginationposition && $this->item->paginationrelative) {
        echo $this->item->pagination;
    }
    ?>

    <?php $useDefList = $params->get('show_modify_date') || $params->get('show_publish_date') || $params->get('show_create_date')
    || $params->get('show_hits') || $params->get('show_category') || $params->get('show_parent_category') || $params->get('show_author') || $assocParam; ?>

    <?php if ($params->get('show_title')) : ?>
    <div class="page-header">
        <<?php echo $htag; ?>>
            <?php echo $this->escape($this->item->title); ?>
        </<?php echo $htag; ?>>
        <?php if ($this->item->state == ContentComponent::CONDITION_UNPUBLISHED) : ?>
            <span class="badge bg-warning text-light"><?php echo Text::_('JUNPUBLISHED'); ?></span>
        <?php endif; ?>
        <?php if ($isNotPublishedYet) : ?>
            <span class="badge bg-warning text-light"><?php echo Text::_('JNOTPUBLISHEDYET'); ?></span>
        <?php endif; ?>
        <?php if ($isExpired) : ?>
            <span class="badge bg-warning text-light"><?php echo Text::_('JEXPIRED'); ?></span>
        <?php endif; ?>
    </div>
    <?php endif; ?>
    <?php if ($canEdit) : ?>
        <?php echo LayoutHelper::render('joomla.content.icons', ['params' => $params, 'item' => $this->item]); ?>
    <?php endif; ?>

    <?php // Content is generated by content plugin event "onContentAfterTitle" ?>
    <?php echo $this->item->event->afterDisplayTitle; ?>

    <?php if ($useDefList && ($info == 0 || $info == 2)) : ?>
        <?php echo LayoutHelper::render('joomla.content.info_block', ['item' => $this->item, 'params' => $params, 'position' => 'above']); ?>
    <?php endif; ?>

    <?php if ($info == 0 && $params->get('show_tags', 1) && !empty($this->item->tags->itemTags)) : ?>
        <?php $this->item->tagLayout = new FileLayout('joomla.content.tags'); ?>

        <?php echo $this->item->tagLayout->render($this->item->tags->itemTags); ?>
    <?php endif; ?>

    <?php // KTC : fiche chantier — mise en forme automatique en tête d'article
    //   des champs du groupe « Fiche chantier » (titres exacts du M01,
    //   docs/guides/02-configuration-site.md §5b). Le rédacteur remplit les
    //   champs ; cet override assure l'affichage. Les valeurs préparées par
    //   com_fields sont sûres pour l'affichage HTML (FieldsHelper). ?>
    <?php
    $ktcTitresFiche = ['Statut du chantier', 'Date de décision', 'Budget estimé', 'Coût constaté', 'Avancement'];
    $ktcFiche = [];

    if (!empty($this->item->jcfields)) {
        foreach ($this->item->jcfields as $ktcChamp) {
            $ktcTitre = trim((string) ($ktcChamp->title ?? ''));

            if ($ktcTitre !== '' && in_array($ktcTitre, $ktcTitresFiche, true)
                && $ktcChamp->value !== null && trim((string) $ktcChamp->value) !== '') {
                $ktcFiche[$ktcTitre] = $ktcChamp;
            }
        }
    }
    ?>
    <?php if (!empty($ktcFiche)) : ?>
    <?php
    $ktcStatut = isset($ktcFiche['Statut du chantier']) ? trim((string) $ktcFiche['Statut du chantier']->value) : '';
    $ktcClasseStatut = 'badge-ktc-etude';

    if ($ktcStatut === 'En cours') {
        $ktcClasseStatut = 'badge-ktc-encours';
    } elseif ($ktcStatut === 'Terminé') {
        $ktcClasseStatut = 'badge-ktc-termine';
    }
    ?>
    <aside class="ktc-fiche-chantier">
        <?php if ($ktcStatut !== '') : ?>
        <span class="badge <?php echo $this->escape($ktcClasseStatut); ?>"><?php echo $ktcFiche['Statut du chantier']->value; ?></span>
        <?php endif; ?>
        <?php if (isset($ktcFiche['Avancement'])) : ?>
        <?php $ktcAvancement = max(0, min(100, (int) $ktcFiche['Avancement']->rawvalue)); ?>
        <div class="ktc-chantier-avancement">
            <span class="visually-hidden">Avancement : <?php echo $ktcAvancement; ?> %</span>
            <span class="ktc-chantier-barre <?php echo $ktcClasseStatut === 'badge-ktc-termine' ? 'ktc-barre-termine' : ($ktcClasseStatut === 'badge-ktc-encours' ? 'ktc-barre-encours' : ''); ?>" aria-hidden="true"><span style="width: <?php echo $ktcAvancement; ?>%;"></span></span>
            <span class="ktc-chantier-pourcentage"><?php echo $ktcAvancement; ?> %</span>
        </div>
        <?php endif; ?>
        <?php if (isset($ktcFiche['Budget estimé']) || isset($ktcFiche['Coût constaté']) || isset($ktcFiche['Date de décision'])) : ?>
        <div class="ktc-chantier-chiffres">
            <?php if (isset($ktcFiche['Budget estimé'])) : ?>
            <div><span class="ktc-chantier-etiquette">Budget estimé</span><strong><?php echo $ktcFiche['Budget estimé']->value; ?></strong></div>
            <?php endif; ?>
            <?php if (isset($ktcFiche['Coût constaté'])) : ?>
            <div><span class="ktc-chantier-etiquette">Coût constaté</span><strong><?php echo $ktcFiche['Coût constaté']->value; ?></strong></div>
            <?php endif; ?>
            <?php if (isset($ktcFiche['Date de décision'])) : ?>
            <div><span class="ktc-chantier-etiquette">Date de décision</span><strong><?php echo $ktcFiche['Date de décision']->value; ?></strong></div>
            <?php endif; ?>
        </div>
        <?php endif; ?>
    </aside>
    <?php endif; ?>

    <?php // Content is generated by content plugin event "onContentBeforeDisplay" ?>
    <?php echo $this->item->event->beforeDisplayContent; ?>

    <?php if ((int) $params->get('urls_position', 0) === 0) : ?>
        <?php echo $this->loadTemplate('links'); ?>
    <?php endif; ?>
    <?php if ($params->get('access-view')) : ?>
        <?php echo LayoutHelper::render('joomla.content.full_image', $this->item); ?>
        <?php
        if (!empty($this->item->pagination) && !$this->item->paginationposition && !$this->item->paginationrelative) :
            echo $this->item->pagination;
        endif;
        ?>
        <?php if (isset($this->item->toc)) :
            echo $this->item->toc;
        endif; ?>
    <div class="com-content-article__body">
        <?php echo $this->item->text; ?>
    </div>

        <?php if ($info == 1 || $info == 2) : ?>
            <?php if ($useDefList) : ?>
                <?php echo LayoutHelper::render('joomla.content.info_block', ['item' => $this->item, 'params' => $params, 'position' => 'below']); ?>
            <?php endif; ?>
            <?php if ($params->get('show_tags', 1) && !empty($this->item->tags->itemTags)) : ?>
                <?php $this->item->tagLayout = new FileLayout('joomla.content.tags'); ?>
                <?php echo $this->item->tagLayout->render($this->item->tags->itemTags); ?>
            <?php endif; ?>
        <?php endif; ?>

        <?php
        if (!empty($this->item->pagination) && $this->item->paginationposition && !$this->item->paginationrelative) :
            echo $this->item->pagination;
            ?>
        <?php endif; ?>
        <?php if ((int) $params->get('urls_position', 0) === 1) : ?>
            <?php echo $this->loadTemplate('links'); ?>
        <?php endif; ?>
        <?php // Optional teaser intro text for guests ?>
    <?php elseif ($params->get('show_noauth') && $user->guest) : ?>
        <?php echo LayoutHelper::render('joomla.content.intro_image', $this->item); ?>
        <?php echo HTMLHelper::_('content.prepare', $this->item->introtext); ?>
        <?php // Optional link to let them register to see the whole article. ?>
        <?php if ($params->get('show_readmore') && $this->item->fulltext != null) : ?>
            <?php $menu = Factory::getApplication()->getMenu(); ?>
            <?php $active = $menu->getActive(); ?>
            <?php $itemId = $active->id; ?>
            <?php $link = new Uri(Route::_('index.php?option=com_users&view=login&Itemid=' . $itemId, false)); ?>
            <?php $link->setVar('return', base64_encode(RouteHelper::getArticleRoute($this->item->slug, $this->item->catid, $this->item->language))); ?>
            <?php echo LayoutHelper::render('joomla.content.readmore', ['item' => $this->item, 'params' => $params, 'link' => $link]); ?>
        <?php endif; ?>
    <?php endif; ?>
    <?php
    if (!empty($this->item->pagination) && $this->item->paginationposition && $this->item->paginationrelative) :
        echo $this->item->pagination;
        ?>
    <?php endif; ?>
    <?php // Content is generated by content plugin event "onContentAfterDisplay" ?>
    <?php echo $this->item->event->afterDisplayContent; ?>
</div>
